        document.addEventListener('DOMContentLoaded', function() {
            const backToTopBtn = document.getElementById('backToTopBtn');
            if (backToTopBtn) {
                window.addEventListener('scroll', function() {
                    if (window.scrollY > 300) {
                        backToTopBtn.classList.remove('opacity-0', 'translate-y-10', 'pointer-events-none');
                        backToTopBtn.classList.add('opacity-100', 'translate-y-0');
                    } else {
                        backToTopBtn.classList.remove('opacity-100', 'translate-y-0');
                        backToTopBtn.classList.add('opacity-0', 'translate-y-10', 'pointer-events-none');
                    }
                });

                backToTopBtn.addEventListener('click', function() {
                    window.scrollTo({
                        top: 0,
                        behavior: 'smooth'
                    });
                });
            }

            // Gọi API tải động danh mục chính cho footer
            loadFooterCategories();
        });

        async function loadFooterCategories() {
            const footerListEl = document.getElementById("footer-categories-list");
            if (!footerListEl) return;
            try {
                const res = await fetch("/Project-Web-Programming/backend/public/index.php/api/categories");
                if (res.ok) {
                    const categories = await res.json();
                    const items = Array.isArray(categories) ? categories : (categories.data || []);
                    if (items.length > 0) {
                        footerListEl.innerHTML = items.slice(0, 5).map(cat => {
                            let icon = 'category';
                            const name = cat.Name.toLowerCase();
                            if (name.includes('điện tử') || name.includes('công nghệ')) icon = 'devices';
                            else if (name.includes('điện thoại') || name.includes('máy tính bảng')) icon = 'smartphone';
                            else if (name.includes('nội thất') || name.includes('gia dụng')) icon = 'home';
                            else if (name.includes('thời trang') || name.includes('quần áo')) icon = 'checkroom';
                            else if (name.includes('xe cộ') || name.includes('phụ tùng')) icon = 'directions_car';
                            else if (name.includes('sách')) icon = 'menu_book';
                            
                            return `
                                <li>
                                    <a href="/Project-Web-Programming/frontend/pages/products/category.php?category=${cat.ID || cat.id}" class="hover:text-blue-400 transition-colors flex items-center gap-2">
                                        <span class="material-symbols-outlined text-[16px] text-blue-500">${icon}</span> ${cat.Name}
                                    </a>
                                </li>
                            `;
                        }).join('');
                    }
                }
            } catch (e) {
                console.error("Lỗi tải danh mục footer:", e);
            }
        }
    </script>
